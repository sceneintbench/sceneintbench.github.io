(() => {
  const section = document.getElementById('scene-examples');
  const dialog = document.getElementById('scene-metrics-dialog');
  const dataElement = document.getElementById('scene-example-metrics');
  if (!section || !dialog || !dataElement) return;
  const records = JSON.parse(dataElement.textContent);
  const title = document.getElementById('scene-metrics-title');
  const meta = document.getElementById('scene-metrics-meta');
  const image = document.getElementById('scene-metrics-image');
  const viewSelect = document.getElementById('scene-metrics-view');
  const prompt = document.getElementById('scene-metrics-prompt');
  const values = document.getElementById('scene-metrics-values');
  let opener;
  let activeRecord;
  const viewLabels = {
    corner_sw: 'Corner SW',
    corner_se: 'Corner SE',
    corner_ne: 'Corner NE',
    corner_nw: 'Corner NW',
    topdown: 'Top-down'
  };

  const groups = [
    { name: 'Semantic Quality', kind: 'semantic', metrics: [
      ['realism', 'Real', 'Realism', '↑', '0–10'],
      ['functionality', 'Func', 'Functionality', '↑', '0–10'],
      ['layout', 'Lay', 'Layout', '↑', '0–10'],
      ['completion', 'Comp', 'Completeness', '↑', '0–10']
    ] },
    { name: 'Static Physical Plausibility', kind: 'static', metrics: [
      ['collision_percent', 'COL', 'Collision rate', '↓', '%'],
      ['out_of_bound_percent', 'OB', 'Out-of-bounds', '↓', '%'],
      ['support_percent', 'SUP', 'Support', '↑', '%'],
      ['stability_native_percent', 'STAB', 'Stability', '↑', '%']
    ] },
    { name: 'Interactive Physical Plausibility', kind: 'interactive', metrics: [
      ['ie_success_percent', 'ISR', 'Interaction success rate', '↑', '%'],
      ['ie_score', 'ICP', 'Interaction capability progress', '↑', '0–10'],
      ['damage_rate_percent', 'PIV', 'Post-interaction violation rate', '↓', '%'],
      ['dp', 'DP', 'Dynamic plausibility', '↑', '0–10']
    ] }
  ];

  function element(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function selectView(view) {
    if (!activeRecord || !viewLabels[view]) return;
    const source = activeRecord.views?.[view] || (view === 'corner_sw' ? activeRecord.image : null);
    if (!source) return;
    viewSelect.value = view;
    image.src = source;
    image.alt = `${viewLabels[view]} view of ${activeRecord.room} generated by ${activeRecord.method}, ${activeRecord.scene}`;
  }

  function openMetrics(trigger) {
    const record = records[trigger.dataset.metricsKey];
    if (!record) return;
    opener = trigger;
    activeRecord = record;
    title.textContent = `${record.room} · ${record.method}`;
    meta.textContent = `Scene ${record.scene.replace('scene', '')} · ${record.tasks} interaction tasks · ${record.coverage.executed_cases} executed`;
    selectView('corner_sw');
    prompt.textContent = record.prompt;
    values.replaceChildren();
    groups.forEach(group => {
      const block = element('section', `scene-metric-group scene-metric-${group.kind}`);
      block.append(element('h3', '', group.name));
      const list = element('dl', 'scene-metric-values');
      group.metrics.forEach(([key, short, label, direction, unit]) => {
        const item = element('div', 'scene-metric-item');
        const term = element('dt', '', `${short} ${direction}`);
        term.title = `${label}; ${direction === '↑' ? 'higher' : 'lower'} is better`;
        const value = record.metrics[key];
        const result = element('dd');
        if (value === null || value === undefined) {
          result.append(element('span', 'scene-metric-number scene-metric-unavailable', 'Not Support Action'));
        } else {
          result.append(element('span', 'scene-metric-number', value.toFixed(2)));
          result.append(element('span', 'scene-metric-unit', unit));
          const countKey = key === 'damage_rate_percent' ? 'post_metrics_n' : key === 'dp' ? 'dp_n' : null;
          if (countKey && Number.isInteger(record.coverage[countKey])) {
            result.append(element('span', 'scene-metric-count', `n = ${record.coverage[countKey]} tasks`));
          }
        }
        item.append(term, result);
        list.append(item);
      });
      block.append(list);
      values.append(block);
    });
    dialog.showModal();
    dialog.scrollTop = 0;
    document.body.classList.add('scene-metrics-open');
  }

  section.querySelectorAll('.scene-metrics-trigger').forEach(trigger => {
    trigger.addEventListener('click', () => openMetrics(trigger));
  });
  viewSelect.addEventListener('change', () => selectView(viewSelect.value));
  dialog.querySelector('.scene-metrics-close').addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', event => {
    if (event.target === dialog) dialog.close();
  });
  dialog.addEventListener('close', () => {
    document.body.classList.remove('scene-metrics-open');
    if (opener?.isConnected) opener.focus();
  });
})();
